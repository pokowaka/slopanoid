#!/usr/bin/env node
/* Plays every solution script (tools/scripts.js) through the real simulation and
 * writes the frame-exact attract-mode recordings to js/solutions.js.
 *   node tools/solve.js          regenerate all
 *   node tools/solve.js 2-1      only print one level (does not write) */
'use strict';
const fs = require('fs');
const path = require('path');
const lib = require('./lib');
const BT = lib.load(['solutions', 'font', 'sprites', 'render']);
const scripts = require('./scripts');
const only = process.argv[2];

const out = {};
let bad = 0;
for (const level of BT.LEVELS) {
  if (only && level.id !== only) continue;
  const rules = scripts[level.id];
  if (!rules) { console.log(`${level.id.padEnd(4)} NO SCRIPT`); bad++; continue; }
  const r = lib.solve(BT, level, rules);
  const s = r.sim, ok = s.win && !r.warn.length;
  if (!ok) bad++;
  out[level.id] = r.cmds;
  console.log(`${level.id.padEnd(4)} ${ok ? 'OK  ' : 'FAIL'} saved ${String(s.saved).padStart(2)}/${String(s.num).padEnd(2)} ${String(s.pct).padStart(3)}% (need ${level.need}%)  cmds ${r.cmds.length}  ` +
    `time ${(s.frame / 60).toFixed(0)}s/${level.time}s  stems ${s.stems}  on-beat ${s.onBeats}/${s.assigns}  ${level.name}`);
  r.warn.forEach(w => console.log('     WARN ' + w));
}
if (!only) {
  let js = '/* BEAT TRIBE - attract-mode solution recordings.\n' +
    ' * GENERATED by `node tools/solve.js` from tools/scripts.js - do not edit by hand.\n' +
    ' * Each command is {frame, lemmingIndex, skill}; {frame, nuke:true} presses the nuke button and\n' +
    ' * {frame, rr:n} sets the release rate.  `node tools/verify.js` replays these to prove every level is solvable. */\n' +
    "(function (g) {\n  'use strict';\n  g.BT.SOLUTIONS = {\n";
  js += BT.LEVELS.filter(l => out[l.id]).map(l => `    '${l.id}': [\n` + out[l.id].map(c => {
    if (c.nuke) return `      { frame: ${c.frame}, nuke: true }`;
    if (c.rr !== undefined) return `      { frame: ${c.frame}, rr: ${c.rr} }`;
    return `      { frame: ${c.frame}, lemmingIndex: ${c.lemmingIndex}, skill: '${c.skill}' }`;
  }).join(',\n') + '\n    ]').join(',\n');
  js += "\n  };\n})(typeof window !== 'undefined' ? window : globalThis);\n";
  fs.writeFileSync(path.join(lib.ROOT, 'js', 'solutions.js'), js);
  console.log(`wrote js/solutions.js (${Object.keys(out).length} levels)${bad ? '  ** ' + bad + ' PROBLEM(S) **' : ''}`);
}
process.exit(bad ? 1 : 0);
